import { useCallback, useEffect, useState } from "react";
import { ArrowLeft, ArrowUpRight, Bot, Check, CheckCheck, Crosshair, Download, ExternalLink, GitMerge, RotateCw, Search, ShieldOff, UserPlus } from "lucide-react";
import { api } from "../services/api.js";
import { useAuth } from "../auth.jsx";
import { alertLabel } from "../components/AlertsPanel.jsx";
import { openDeviceViewer } from "../components/DeviceViewer.jsx";
import { sourceParam, useEnvironment } from "../services/environment.js";

const STATES = ["new", "acknowledged", "investigating", "escalated", "closed"];
const when = (iso) => (iso ? new Date(iso).toLocaleString() : "—");
const time = (iso) => (iso ? new Date(iso).toLocaleTimeString() : "—");

export function Confidence({ value }) {
  return <span className="conf" title="Rule confidence: how likely this alert is a real attack"><i><b style={{ width: `${value * 100}%` }} /></i>{Math.round(value * 100)}%</span>;
}
export function Mitre({ m }) {
  if (!m) return <span className="muted small">—</span>;
  return <a className="mitre" href={m.url} target="_blank" rel="noreferrer" title={`${m.name} · ${m.tactic}`}>{m.id}</a>;
}
export function SourceBadge({ source }) {
  return <span className={`src-badge src-${source}`} title={source === "lab" ? "Real test board" : "Generated by the simulator"}>{source === "lab" ? "LAB" : "SIM"}</span>;
}

function exportCsv(rows) {
  const cols = ["id", "timestamp", "severity", "rule_id", "rule_name", "device_id", "state", "assignee", "confidence", "source", "description"];
  const esc = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;
  const csv = [cols.join(","), ...rows.map((r) => cols.map((c) => esc(c === "mitre" ? r.mitre?.id : r[c])).join(","))].join("\n");
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([csv], { type: "text/csv" }));
  a.download = "cybershield-alerts.csv";
  a.click();
  URL.revokeObjectURL(a.href);
}

function AlertList({ refreshKey, onOpen }) {
  const env = useEnvironment();
  const [f, setF] = useState({ status: "open", severity: "", state: "", rule_id: "", q: "", hours: 168 });
  const [data, setData] = useState(null);
  const [rules, setRules] = useState([]);
  const [err, setErr] = useState(null);
  const load = useCallback(() => api.socAlerts({ ...f, source: sourceParam(env), limit: 300 }).then((r) => { setData(r); setErr(null); }).catch((e) => setErr(e.message)), [f, env]);
  useEffect(() => { load(); }, [load, refreshKey]);
  useEffect(() => { api.socRules().then((r) => setRules(r.rules)).catch(() => {}); }, []);
  const set = (k) => (e) => setF({ ...f, [k]: e.target.value });

  if (env === "production") {
    return <section className="panel notice"><b>Production selected.</b> No production data source is connected in this project, so there are no
      production alerts. Choose Simulation, Lab or All sources in the top bar.</section>;
  }
  return (
    <section className="panel">
      <div className="filter-bar">
        <div className="global-search" style={{ width: "auto", flex: 1, maxWidth: 380 }}>
          <Search size={14} />
          <input type="search" value={f.q} onChange={set("q")} placeholder="Search ID, device, rule, MITRE (e.g. T1498), analyst…" />
        </div>
        <select value={f.status} onChange={set("status")} aria-label="Status">
          <option value="open">Open</option><option value="resolved">Resolved</option><option value="all">All</option>
        </select>
        <select value={f.severity} onChange={set("severity")} aria-label="Severity">
          <option value="">All severities</option><option value="critical">Critical</option><option value="high">High</option>
          <option value="critical,high">High + critical</option><option value="medium">Medium</option><option value="low">Low</option>
        </select>
        <select value={f.state} onChange={set("state")} aria-label="Investigation state">
          <option value="">Any state</option>{STATES.map((s) => <option key={s} value={s}>{s}</option>)}
        </select>
        <select value={f.rule_id} onChange={set("rule_id")} aria-label="Rule">
          <option value="">All rules</option>{rules.map((r) => <option key={r.id} value={r.id}>{r.id} · {r.name}</option>)}
        </select>
        <select value={f.hours} onChange={set("hours")} aria-label="Time range">
          {[[1, "1 h"], [24, "24 h"], [168, "7 days"], [720, "30 days"]].map(([h, l]) => <option key={h} value={h}>Last {l}</option>)}
        </select>
        <button className="btn btn-small" onClick={load}><RotateCw size={13} /> Refresh</button>
        <button className="btn btn-small" disabled={!data?.alerts.length} onClick={() => exportCsv(data.alerts)}><Download size={13} /> CSV</button>
      </div>
      {data && (
        <div className="small muted" style={{ marginBottom: 8 }}>
          {data.count} alerts · {STATES.map((s) => `${data.states[s] ?? 0} ${s}`).join(" · ")}
        </div>
      )}
      {err && <div className="tone-bad small">{err}</div>}
      <div className="table-wrap" style={{ maxHeight: 620 }}>
        <table className="data-table">
          <thead><tr>
            <th>Severity</th><th>ID</th><th>Detection</th><th>Device</th><th>MITRE</th><th>Confidence</th><th>Src</th><th>State</th><th>Analyst</th><th>Time</th>
          </tr></thead>
          <tbody>
            {data?.alerts.map((a) => (
              <tr key={a.id} className="clickable" onClick={() => onOpen(a.id)}>
                <td><span className={`sev sev-${a.severity}`}>{a.severity}</span></td>
                <td className="mono">#{a.id}</td>
                <td>
                  <div>{a.rule_name}</div>
                  <div className="small muted">
                    {a.rule_id ?? alertLabel(a.alert_type)}
                    {a.duplicates > 0 && <span title="Same rule on the same device within 30 min"> · ×{a.duplicates + 1} similar</span>}
                    {a.correlation && <span title="Other detections on this device in the same hour"> · <GitMerge size={11} /> correlated</span>}
                  </div>
                </td>
                <td className="mono">{a.device_id ?? "network"}</td>
                <td><Mitre m={a.mitre} /></td>
                <td><Confidence value={a.confidence} /></td>
                <td><SourceBadge source={a.source} /></td>
                <td className={`state state-${a.state}`}>{a.state}</td>
                <td>{a.assignee || <span className="muted">—</span>}</td>
                <td className="small" title={when(a.timestamp)}>{time(a.timestamp)}</td>
              </tr>
            ))}
          </tbody>
        </table>
        {data && data.alerts.length === 0 && <div className="empty">No alerts match these filters.</div>}
      </div>
    </section>
  );
}

function AlertDetail({ id, onBack, devices, refreshKey }) {
  const { user, can, has } = useAuth();
  const [d, setD] = useState(null);
  const [err, setErr] = useState(null);
  const [note, setNote] = useState("");
  const [assignee, setAssignee] = useState("");
  const [users, setUsers] = useState([]);
  const [busy, setBusy] = useState(false);
  const [reqMsg, setReqMsg] = useState(null);
  const load = useCallback(() => api.socAlert(id).then((r) => { setD(r); setErr(null); }).catch((e) => setErr(e.message)), [id]);
  useEffect(() => { load(); }, [load, refreshKey]);
  useEffect(() => { if (can("admin")) api.users().then((r) => setUsers(r.users ?? r)).catch(() => {}); }, [can]);

  async function act(action, extra = {}) {
    setBusy(true);
    try {
      const r = await api.alertAction(id, action, { note, ...extra });
      setD(r);
      setNote("");
      setErr(r.incident_id ? null : null);
    } catch (e) {
      setErr(e.message);
    } finally {
      setBusy(false);
    }
  }

  if (!d) return <section className="panel"><button className="btn btn-small" onClick={onBack}><ArrowLeft size={13} /> Alerts</button><div className="muted" style={{ marginTop: 10 }}>{err ?? "Loading…"}</div></section>;
  const a = d.alert;
  const rule = d.rule;
  const op = has("triage");
  const device = a.device_id ? devices[a.device_id] : null;
  const closed = a.state === "closed";

  return (
    <>
      <section className="panel">
        <div className="panel-head">
          <div style={{ display: "flex", gap: 10, alignItems: "center", flexWrap: "wrap" }}>
            <button className="btn btn-small" onClick={onBack}><ArrowLeft size={13} /> Alerts</button>
            <span className={`sev sev-${a.severity}`}>{a.severity}</span>
            <h2 style={{ margin: 0 }}>#{a.id} {a.rule_name}</h2>
            <span className={`state state-${a.state}`}>· {a.state}</span>
            <SourceBadge source={a.source} />
          </div>
          <span className="small muted">{when(a.timestamp)}</span>
        </div>
        <p style={{ margin: "4px 0 10px" }}>{a.description}</p>
        {op && (
          <div className="filter-bar">
            {!closed && a.state === "new" && <button className="btn btn-small" disabled={busy} onClick={() => act("acknowledge")}><Check size={13} /> Acknowledge</button>}
            {!closed && a.state !== "investigating" && <button className="btn btn-small" disabled={busy} onClick={() => act("investigate")}>Investigate</button>}
            {!closed && a.assignee !== user?.username && <button className="btn btn-small" disabled={busy} onClick={() => act("assign", { assignee: user?.username })}><UserPlus size={13} /> Assign to me</button>}
            {!closed && users.length > 0 && (
              <>
                <select value={assignee} onChange={(e) => setAssignee(e.target.value)} aria-label="Assign to">
                  <option value="">Assign to…</option>{users.map((u) => <option key={u.username} value={u.username}>{u.username} ({u.role})</option>)}
                </select>
                <button className="btn btn-small" disabled={busy || !assignee} onClick={() => act("assign", { assignee })}>Assign</button>
              </>
            )}
            {!closed && a.state !== "escalated" && <button className="btn btn-small btn-warn" disabled={busy} onClick={() => act("escalate")}><ArrowUpRight size={13} /> Escalate to incident</button>}
            {device && device.security_status !== "quarantined" && has("contain") && (
              <button className="btn btn-small btn-danger" disabled={busy} title="Simulated isolation of the device"
                      onClick={() => api.quarantineDevice(a.device_id, `alert #${a.id}: ${a.rule_name}`).then(load).catch((e) => setErr(e.message))}>
                <ShieldOff size={13} /> Quarantine {a.device_id}
              </button>
            )}
            {device && device.security_status !== "quarantined" && !has("contain") && has("contain_request") && (
              <button className="btn btn-small btn-danger" disabled={busy} title="Goes to Approvals: an L3 analyst or the SOC manager decides"
                      onClick={() => api.requestApproval({ action: "isolate_device", target: a.device_id, reason: `alert #${a.id}: ${a.rule_name}`, alert_id: a.id })
                        .then((r) => setReqMsg(`Approval #${r.approval.id} requested.`)).catch((e) => setErr(e.message))}>
                <ShieldOff size={13} /> Request isolation
              </button>
            )}
            {!closed ? <button className="btn btn-small btn-primary" disabled={busy} onClick={() => act("close")}><CheckCheck size={13} /> Close</button>
              : <button className="btn btn-small" disabled={busy} onClick={() => act("reopen")}>Reopen</button>}
          </div>
        )}
        {op && (
          <div className="filter-bar">
            <input style={{ flex: 1 }} value={note} onChange={(e) => setNote(e.target.value)} placeholder="Analyst note (saved with the next action, or alone)" maxLength={2000} />
            <button className="btn btn-small" disabled={busy || !note.trim()} onClick={() => act("note")}>Add note</button>
          </div>
        )}
        <div className="button-row" style={{ marginTop: 6 }}>
          <a className="btn btn-small" href={`#ai?alert=${a.id}`}><Bot size={13} /> Investigate with AI</a>
          {a.device_id && <a className="btn btn-small" href={`#hunting?q=${encodeURIComponent(`device:${a.device_id}`)}`}><Crosshair size={13} /> Hunt {a.device_id}</a>}
        </div>
        {reqMsg && <div className="tone-ok small">{reqMsg} <a href="#approvals">Approvals</a></div>}
        {err && <div className="tone-bad small">{err}</div>}
      </section>

      <div className="grid-main-side">
        <div style={{ display: "flex", flexDirection: "column", gap: 12, minWidth: 0 }}>
          <section className="panel">
            <h2>Detection</h2>
            <dl className="kv">
              <dt>Rule</dt><dd>{rule ? `${rule.id} · ${rule.name} (${rule.kind})` : a.alert_type}</dd>
              <dt>Logic</dt><dd className="mono">{rule?.logic ?? "—"}</dd>
              <dt>Why it matters</dt><dd>{rule?.explanation ?? "—"}</dd>
              <dt>MITRE ATT&amp;CK</dt><dd>{a.mitre ? <a href={a.mitre.url} target="_blank" rel="noreferrer">{a.mitre.id} {a.mitre.name} · {a.mitre.tactic} <ExternalLink size={11} /></a> : "no technique (availability or physical event)"}</dd>
              <dt>Confidence</dt><dd><Confidence value={a.confidence} /> <span className="muted small">rule-based estimate, not a probability measured on real attacks</span></dd>
              <dt>Data source</dt><dd>{rule?.data_source ?? "—"} · <SourceBadge source={a.source} /></dd>
              <dt>Detected by</dt><dd>{a.detection_method === "ml" ? "machine-learning detector" : "rule engine"}</dd>
            </dl>
          </section>

          <section className="panel">
            <h2>Evidence · device events (−10 min … +5 min)</h2>
            {d.evidence.events.length === 0 ? <div className="empty">No events recorded for this device around this time.</div> : (
              <div className="table-wrap" style={{ maxHeight: 260 }}>
                <table className="data-table compact">
                  <thead><tr><th>Time</th><th>Event</th><th>Description</th></tr></thead>
                  <tbody>{d.evidence.events.map((e) => (
                    <tr key={e.id}><td className="small">{time(e.timestamp)}</td><td className="mono small">{e.event_type}</td><td>{e.description}</td></tr>
                  ))}</tbody>
                </table>
              </div>
            )}
          </section>

          <section className="panel">
            <h2>Evidence · readings (−5 min … +2 min)</h2>
            {d.evidence.readings.length === 0 ? <div className="empty">No readings stored for this device around this time.</div> : (
              <div className="table-wrap" style={{ maxHeight: 260 }}>
                <table className="data-table compact">
                  <thead><tr><th>Time</th><th>Temp °C</th><th>Hum %</th><th>Battery %</th><th>Source</th></tr></thead>
                  <tbody>{d.evidence.readings.map((r) => {
                    const out = d.device && (r.temperature < d.device.ranges?.temperature?.[0] || r.temperature > d.device.ranges?.temperature?.[1]);
                    return (
                      <tr key={r.id}><td className="small">{time(r.timestamp)}</td><td className={out ? "tone-bad" : ""}>{r.temperature}</td><td>{r.humidity}</td><td>{r.battery}</td>
                        <td><span className="mono small">{r.source}</span> <SourceBadge source={r.source_mode} /></td></tr>
                    );
                  })}</tbody>
                </table>
              </div>
            )}
          </section>
        </div>

        <div style={{ display: "flex", flexDirection: "column", gap: 12, minWidth: 0 }}>
          <section className="panel">
            <h2>Asset</h2>
            {d.device ? (
              <>
                <dl className="kv">
                  <dt>Device</dt><dd>{d.device.device_id} · {d.device.device_name}</dd>
                  <dt>Type</dt><dd>{d.device.device_type}</dd>
                  <dt>Status</dt><dd>{d.device.status} · {d.device.security_status}</dd>
                  <dt>Connection</dt><dd>{d.device.connection_type}</dd>
                  <dt>Location</dt><dd>{d.device.location || "—"}</dd>
                </dl>
                <div className="button-row" style={{ marginTop: 8 }}>
                  <button className="btn btn-small" onClick={() => openDeviceViewer(d.device.device_id)}>3D model</button>
                  <a className="btn btn-small" href={`#devices/${d.device.device_id}`}>Asset page</a>
                </div>
              </>
            ) : <div className="muted small">{a.device_id ? `${a.device_id} is not a registered device.` : "Network-level alert."}</div>}
          </section>

          <section className="panel">
            <h2>Related alerts (same device ±60 min)</h2>
            {d.evidence.related_alerts.length === 0 ? <div className="empty">None.</div> : (
              <ul className="mini-list">{d.evidence.related_alerts.map((r) => (
                <li key={r.id}><span className={`sev sev-${r.severity}`}>{r.severity}</span><a href={`#alerts/${r.id}`}>#{r.id} {r.rule_name}</a><span className="muted small push-right">{time(r.timestamp)}</span></li>
              ))}</ul>
            )}
          </section>

          <section className="panel">
            <h2>Incidents</h2>
            {d.incidents.length === 0 ? <div className="empty">Not part of an incident. Use “Escalate to incident”.</div> : (
              <ul className="mini-list">{d.incidents.map((i) => (
                <li key={i.id}><a href={`#incidents/${i.id}`}>#{i.id} {i.title}</a><span className="muted small push-right">{i.status}</span></li>
              ))}</ul>
            )}
          </section>

          <section className="panel">
            <h2>Investigation history</h2>
            {d.activity.length === 0 ? <div className="empty">No analyst action yet.</div> : (
              <ol className="incident-timeline">{d.activity.map((x) => (
                <li key={x.id}><div className="small muted">{when(x.created_at)} · <b>{x.username}</b> · {x.action}</div>{x.text && <div>{x.text}</div>}</li>
              ))}</ol>
            )}
          </section>
        </div>
      </div>
    </>
  );
}

// v2.0 Alert Center: triage list (#alerts) and the investigation page of one alert (#alerts/<id>).
export default function AlertCenter({ subId, onNavigate, devices, alerts }) {
  const refreshKey = alerts.length ? `${alerts[0].id}-${alerts.filter((a) => a.status === "open").length}` : "0";
  return subId
    ? <AlertDetail id={subId} onBack={() => onNavigate("alerts")} devices={devices} refreshKey={refreshKey} />
    : <AlertList refreshKey={refreshKey} onOpen={(id) => onNavigate(`alerts/${id}`)} />;
}
